-- Creazione delle tabelle per le fatture e le righe di fattura.
-- il cedente e il destinatario sono memorizzati come JSONB.
-- il tipo JSONB permette di memorizzare strutture dati complesse
-- come oggetti e array.
-- Ad esempio: {"chiave": "valore"}
CREATE TABLE IF NOT EXISTS invoices (
    id INTEGER PRIMARY KEY,
    numero_fattura VARCHAR(64) NOT NULL,
    data DATE NOT NULL,
    cedente JSONB NOT NULL,
    destinatario JSONB NOT NULL
);



CREATE TABLE IF NOT EXISTS invoice_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id INTEGER NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    descrizione VARCHAR(255) NOT NULL,
    quantita NUMERIC NOT NULL,
    prezzo_unitario NUMERIC NOT NULL,
    aliquota_iva NUMERIC NOT NULL,
    sconto_percentuale NUMERIC NOT NULL DEFAULT 0
);

